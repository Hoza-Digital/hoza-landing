create or replace function public.hoza_get_published_article(
  p_backend_secret text,
  p_date_code text,
  p_slug text
)
returns table (
  id bigint,
  title text,
  slug text,
  category text,
  excerpt text,
  content text,
  cover_image_url text,
  cover_image_alt text,
  author_name text,
  seo_title text,
  seo_description text,
  geo_summary text,
  publish_date date,
  published_at timestamptz,
  updated_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.hoza_assert_backend_secret(p_backend_secret);

  return query
  select
    article.id,
    article.title,
    article.slug,
    article.category,
    article.excerpt,
    article.content,
    article.cover_image_url,
    article.cover_image_alt,
    article.author_name,
    article.seo_title,
    article.seo_description,
    article.geo_summary,
    article.publish_date,
    article.published_at,
    article.updated_at
  from public.articles article
  where article.status = 'published'
    and article.published_at <= now()
    and to_char(article.publish_date, 'YYMMDD') = p_date_code
    and article.slug = lower(trim(p_slug))
  limit 1;
end;
$$;

