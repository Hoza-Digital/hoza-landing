begin
  perform private.hoza_assert_backend_secret(p_backend_secret);

  return query
  select u.id, u.email, u.active
  from public.admin_users u
  where u.id = p_id
  limit 1;
end;
$$;

create or replace function public.hoza_admin_upsert_user(
  p_backend_secret text,
  p_email text,
  p_password_hash text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  admin_id bigint;
begin
  perform private.hoza_assert_backend_secret(p_backend_secret);

  if p_email is null or position('@' in p_email) < 2 then
    raise exception 'Invalid admin email' using errcode = '22023';
  end if;

  if p_password_hash is null or p_password_hash not like 'scrypt$%$%' then
    raise exception 'Invalid admin password hash' using errcode = '22023';
  end if;

  insert into public.admin_users (email, password_hash, active)
  values (lower(trim(p_email)), p_password_hash, true)
  on conflict (lower(email)) do update
  set password_hash = excluded.password_hash,
      active = true,
      updated_at = now()
  returning id into admin_id;

  return admin_id;
end;
$$;

