create or replace function private.hoza_assert_backend_secret(p_backend_secret text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_backend_secret is null or not exists (
    select 1
    from private.hoza_config
    where config_key = 'backend_secret_sha256'
      and value_hash = extensions.digest(p_backend_secret, 'sha256')
  ) then
    raise exception 'Unauthorized backend request' using errcode = '42501';
  end if;
end;
$$;

revoke all on function private.hoza_assert_backend_secret(text) from public, anon, authenticated;

create or replace function public.hoza_create_enquiry(
  p_backend_secret text,
  p_name text,
  p_company text,
  p_email text,
  p_whatsapp text,
  p_country text,
  p_service text,
  p_description text,
  p_budget text,
  p_timeline text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  enquiry_id bigint;
begin
  perform private.hoza_assert_backend_secret(p_backend_secret);

  insert into public.enquiries (
    name, company, email, whatsapp, country, service,
    description, budget, timeline
  ) values (
    p_name, coalesce(p_company, ''), p_email, coalesce(p_whatsapp, ''),
    p_country, p_service, p_description, p_budget, p_timeline
  )
  returning id into enquiry_id;

  return enquiry_id;
end;
$$;

create or replace function public.hoza_admin_list_enquiries(p_backend_secret text)
returns table (
  id bigint,
  name text,
  company text,
  email text,
  whatsapp text,
  country text,
  service text,
  description text,
  budget text,
  timeline text,
  status text,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.hoza_assert_backend_secret(p_backend_secret);

  return query
  select
    e.id, e.name, e.company, e.email, e.whatsapp, e.country,
    e.service, e.description, e.budget, e.timeline, e.status, e.created_at
  from public.enquiries e
  order by e.created_at desc
  limit 500;
end;
$$;

create or replace function public.hoza_admin_enquiry_stats(p_backend_secret text)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  result jsonb;
begin
  perform private.hoza_assert_backend_secret(p_backend_secret);

  select jsonb_build_object(
    'total', count(*),
    'fresh', count(*) filter (where status = 'new'),
    'recent', count(*) filter (where created_at >= now() - interval '30 days'),
    'services', count(distinct service)
  )
  into result
  from public.enquiries;

  return result;
end;
$$;

create or replace function public.hoza_admin_update_enquiry_status(
  p_backend_secret text,
  p_id bigint,
  p_status text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.hoza_assert_backend_secret(p_backend_secret);

  if p_status not in ('new', 'reviewing', 'contacted', 'archived') then
    raise exception 'Invalid enquiry status' using errcode = '22023';
  end if;

  update public.enquiries
  set status = p_status
  where id = p_id;
end;
$$;

create or replace function public.hoza_admin_get_user_by_email(
  p_backend_secret text,
  p_email text
)
returns table (id bigint, email text, password_hash text, active boolean)
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform private.hoza_assert_backend_secret(p_backend_secret);

  return query
  select u.id, u.email, u.password_hash, u.active
  from public.admin_users u
  where lower(u.email) = lower(trim(p_email))
  limit 1;
end;
$$;

create or replace function public.hoza_admin_get_user_by_id(
  p_backend_secret text,
  p_id bigint
)
